package com.odin.core.network.rules;

import androidx.annotation.NonNull;
import androidx.annotation.Nullable;

import com.odin.core.network.detection.DetectionResult;
import com.odin.core.network.detection.ThreatLevel;

import java.io.Serializable;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.Map;
import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.CopyOnWriteArrayList;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;
import java.util.concurrent.ScheduledExecutorService;
import java.util.concurrent.ScheduledThreadPoolExecutor;
import java.util.concurrent.TimeUnit;
import java.util.concurrent.atomic.AtomicLong;

/**
 * DynamicRuleEngine: Motor de reglas dinámicas y adaptativas.
 * 
 * Implementa:
 * - Event-Based Rules (EBR)
 * - Reglas contextuales
 * - Auto-generación de reglas
 * - Expiración automática de reglas
 * - Resolución de conflictos
 * 
 * Performance: <1ms evaluación por regla
 * Thread-safe: Concurrent maps + thread-safe rule list
 */
public final class DynamicRuleEngine {

    private static final int CLEANUP_INTERVAL_MS = 60_000; // Limpieza cada 60 segundos
    private static final int MAX_RULES = 10_000;

    private final List<FirewallRule> activeRules;
    private final Map<String, Long> ruleLastMatched; // Para tracking
    private final ExecutorService evaluationExecutor;
    private final ScheduledExecutorService cleanupExecutor;
    private final List<RuleEvaluationListener> listeners;
    private final AtomicLong rulesEvaluated;
    private final AtomicLong rulesAutoGenerated;
    private final AtomicLong rulesExpired;
    private final AtomicLong conflictsResolved;

    /**
     * Definición de regla de firewall.
     */
    public static final class FirewallRule implements Serializable, Comparable<FirewallRule> {
        private static final long serialVersionUID = 1L;

        private final String ruleId;
        private final String name;
        private final RulePriority priority;
        private final RuleAction action; // ALLOW, BLOCK, QUARANTINE, ALERT
        private final String sourceIPPattern; // "*" o rango IP
        private final String destIPPattern;
        private final Integer sourcePort; // null = cualquier puerto
        private final Integer destPort;
        private final Integer protocol; // null = cualquier protocolo
        private final String threatTypePattern; // Patrón de tipo de amenaza
        private final long createdTime;
        private volatile long expirationTime; // 0 = no expira
        private volatile boolean enabled;
        private volatile int matchCount;

        public FirewallRule(
                String name,
                RulePriority priority,
                RuleAction action,
                String sourceIPPattern,
                String destIPPattern,
                @Nullable Integer sourcePort,
                @Nullable Integer destPort,
                @Nullable Integer protocol,
                String threatTypePattern
        ) {
            this.ruleId = generateRuleId();
            this.name = name;
            this.priority = priority;
            this.action = action;
            this.sourceIPPattern = sourceIPPattern;
            this.destIPPattern = destIPPattern;
            this.sourcePort = sourcePort;
            this.destPort = destPort;
            this.protocol = protocol;
            this.threatTypePattern = threatTypePattern;
            this.createdTime = System.currentTimeMillis();
            this.expirationTime = 0; // No expira por defecto
            this.enabled = true;
            this.matchCount = 0;
        }

        public String getRuleId() { return ruleId; }
        public String getName() { return name; }
        public RulePriority getPriority() { return priority; }
        public RuleAction getAction() { return action; }
        public long getCreatedTime() { return createdTime; }
        public long getExpirationTime() { return expirationTime; }
        public boolean isEnabled() { return enabled; }
        public int getMatchCount() { return matchCount; }

        /**
         * Establece expiración de la regla.
         */
        public void setExpiration(long expirationTimeMs) {
            this.expirationTime = System.currentTimeMillis() + expirationTimeMs;
        }

        /**
         * Verifica si la regla ha expirado.
         */
        public boolean hasExpired() {
            return expirationTime > 0 && System.currentTimeMillis() > expirationTime;
        }

        /**
         * Habilita/deshabilita la regla.
         */
        public void setEnabled(boolean enabled) {
            this.enabled = enabled;
        }

        /**
         * Incrementa contador de coincidencias.
         */
        public void incrementMatchCount() {
            this.matchCount++;
        }

        /**
         * Evaluación básica de si un paquete coincide con esta regla.
         */
        public boolean matches(String srcIP, String dstIP, @Nullable Integer srcPort, @Nullable Integer dstPort, @Nullable Integer proto, String threatType) {
            if (!enabled || hasExpired()) return false;

            // Evaluar cada condición
            if (!matchesIP(srcIP, sourceIPPattern)) return false;
            if (!matchesIP(dstIP, destIPPattern)) return false;

            if (sourcePort != null && (srcPort == null || !srcPort.equals(this.sourcePort))) return false;
            if (destPort != null && (dstPort == null || !dstPort.equals(this.destPort))) return false;

            if (protocol != null && (proto == null || !proto.equals(this.protocol))) return false;

            if (!threatType.matches(threatTypePattern)) return false;

            return true;
        }

        private boolean matchesIP(String ip, String pattern) {
            if ("*".equals(pattern)) return true;

            // Simple pattern matching: "192.168.*" o "192.168.1.1"
            return ip.startsWith(pattern.replace("*", ""));
        }

        private static String formatIP(String ip) {
            return ip;
        }

        private static String generateRuleId() {
            return "RULE_" + System.currentTimeMillis() + "_" + (int)(Math.random() * 10000);
        }

        @Override
        public int compareTo(@NonNull FirewallRule other) {
            // Comparar por prioridad descendente
            int priorityComparison = Integer.compare(
                    other.priority.getValue(),
                    this.priority.getValue()
            );
            if (priorityComparison != 0) return priorityComparison;

            // Si misma prioridad, por fecha de creación descendente
            return Long.compare(other.createdTime, this.createdTime);
        }

        @Override
        public String toString() {
            return String.format(
                    "Rule{%s: %s [%s] %s -> %s, matches=%d}",
                    ruleId, name, priority.name(), sourceIPPattern, destIPPattern, matchCount
            );
        }
    }

    public enum RulePriority {
        CRITICAL(4),
        HIGH(3),
        MEDIUM(2),
        LOW(1),
        INFO(0);

        private final int value;
        RulePriority(int value) { this.value = value; }
        public int getValue() { return value; }
    }

    public enum RuleAction {
        ALLOW,        // Permitir conexión
        BLOCK,        // Bloquear conexión
        QUARANTINE,   // Aislar tráfico
        ALERT,        // Solo alertar sin bloquear
        RATE_LIMIT    // Limitar velocidad
    }

    /**
     * Listener para evaluaciones de reglas.
     */
    public interface RuleEvaluationListener {
        void onRuleMatched(FirewallRule rule, String srcIP, String dstIP);
        void onRuleCreated(FirewallRule rule);
        void onRuleExpired(FirewallRule rule);
    }

    public DynamicRuleEngine() {
        this.activeRules = new CopyOnWriteArrayList<>();
        this.ruleLastMatched = new ConcurrentHashMap<>();
        this.listeners = new CopyOnWriteArrayList<>();
        this.rulesEvaluated = new AtomicLong(0);
        this.rulesAutoGenerated = new AtomicLong(0);
        this.rulesExpired = new AtomicLong(0);
        this.conflictsResolved = new AtomicLong(0);

        this.evaluationExecutor = Executors.newFixedThreadPool(2, r -> {
            Thread t = new Thread(r, "RuleEvaluator");
            t.setDaemon(true);
            return t;
        });

        this.cleanupExecutor = new ScheduledThreadPoolExecutor(1, r -> {
            Thread t = new Thread(r, "RuleCleanup");
            t.setDaemon(true);
            return t;
        });

        // Inicia limpieza periódica
        cleanupExecutor.scheduleAtFixedRate(
                this::cleanupExpiredRules,
                CLEANUP_INTERVAL_MS,
                CLEANUP_INTERVAL_MS,
                TimeUnit.MILLISECONDS
        );
    }

    /**
     * Añade una regla al engine.
     */
    public void addRule(@NonNull FirewallRule rule) {
        if (activeRules.size() >= MAX_RULES) {
            // Remover regla menos usada
            activeRules.stream()
                    .min((a, b) -> Integer.compare(a.getMatchCount(), b.getMatchCount()))
                    .ifPresent(activeRules::remove);
        }

        activeRules.add(rule);
        // Mantener ordenadas por prioridad
        Collections.sort(activeRules);
        
        notifyRuleCreated(rule);
    }

    /**
     * Remueve una regla.
     */
    public void removeRule(@NonNull String ruleId) {
        activeRules.removeIf(r -> r.getRuleId().equals(ruleId));
    }

    /**
     * Evalúa si un paquete coincide con alguna regla.
     * 
     * @return Primera regla que coincida, o null
     */
    @Nullable
    public FirewallRule evaluatePacket(
            String srcIP, String dstIP,
            @Nullable Integer srcPort, @Nullable Integer dstPort,
            @Nullable Integer protocol,
            String threatType
    ) {
        rulesEvaluated.incrementAndGet();

        // Evaluar reglas en orden de prioridad
        for (FirewallRule rule : activeRules) {
            if (rule.matches(srcIP, dstIP, srcPort, dstPort, protocol, threatType)) {
                rule.incrementMatchCount();
                notifyRuleMatched(rule, srcIP, dstIP);
                return rule;
            }
        }

        return null;
    }

    /**
     * Evalúa un resultado de detección contra las reglas.
     * 
     * @return Acción recomendada (BLOCK, ALLOW, ALERT, etc.)
     */
    @NonNull
    public RuleAction evaluateDetection(@NonNull DetectionResult detection) {
        FirewallRule matchedRule = evaluatePacket(
                detection.getSourceIp(),
                detection.getDestinationIp(),
                detection.getSourcePort(),
                detection.getDestinationPort(),
                null,
                detection.getThreatType()
        );

        if (matchedRule != null) {
            return matchedRule.getAction();
        }

        // Acción por defecto según severidad
        return switch (detection.getThreatLevel()) {
            case CRITICAL -> RuleAction.BLOCK;
            case HIGH -> RuleAction.QUARANTINE;
            case MEDIUM -> RuleAction.ALERT;
            default -> RuleAction.ALLOW;
        };
    }

    /**
     * Crea una regla automáticamente basada en una detección.
     */
    public FirewallRule autoGenerateRule(@NonNull DetectionResult detection) {
        FirewallRule rule = new FirewallRule(
                "Auto-" + detection.getThreatType(),
                RulePriority.MEDIUM,
                RuleAction.BLOCK,
                formatIP(detection.getSourceIp()),
                formatIP(detection.getDestinationIp()),
                detection.getSourcePort(),
                detection.getDestinationPort(),
                null,
                detection.getThreatType() + ".*"
        );

        // Auto-expira en 1 hora
        rule.setExpiration(3600_000);

        addRule(rule);
        rulesAutoGenerated.incrementAndGet();
        return rule;
    }

    /**
     * Obtiene todas las reglas activas.
     */
    public List<FirewallRule> getActiveRules() {
        return new ArrayList<>(activeRules);
    }

    /**
     * Limpia reglas expiradas.
     */
    private void cleanupExpiredRules() {
        List<FirewallRule> toRemove = new ArrayList<>();

        for (FirewallRule rule : activeRules) {
            if (rule.hasExpired()) {
                toRemove.add(rule);
            }
        }

        for (FirewallRule rule : toRemove) {
            activeRules.remove(rule);
            notifyRuleExpired(rule);
            rulesExpired.incrementAndGet();
        }
    }

    /**
     * Registra un listener.
     */
    public void addListener(@NonNull RuleEvaluationListener listener) {
        listeners.add(listener);
    }

    /**
     * Remueve un listener.
     */
    public void removeListener(@NonNull RuleEvaluationListener listener) {
        listeners.remove(listener);
    }

    private void notifyRuleMatched(FirewallRule rule, String srcIP, String dstIP) {
        for (RuleEvaluationListener listener : listeners) {
            try {
                listener.onRuleMatched(rule, srcIP, dstIP);
            } catch (Exception e) {
                // Ignorar errores
            }
        }
    }

    private void notifyRuleCreated(FirewallRule rule) {
        for (RuleEvaluationListener listener : listeners) {
            try {
                listener.onRuleCreated(rule);
            } catch (Exception e) {
                // Ignorar errores
            }
        }
    }

    private void notifyRuleExpired(FirewallRule rule) {
        for (RuleEvaluationListener listener : listeners) {
            try {
                listener.onRuleExpired(rule);
            } catch (Exception e) {
                // Ignorar errores
            }
        }
    }

    private static String formatIP(String ip) {
        return ip;
    }

    /**
     * Cierra el engine.
     */
    public void shutdown() {
        cleanupExecutor.shutdown();
        evaluationExecutor.shutdown();
        try {
            if (!cleanupExecutor.awaitTermination(5, TimeUnit.SECONDS)) {
                cleanupExecutor.shutdownNow();
            }
            if (!evaluationExecutor.awaitTermination(5, TimeUnit.SECONDS)) {
                evaluationExecutor.shutdownNow();
            }
        } catch (InterruptedException e) {
            cleanupExecutor.shutdownNow();
            evaluationExecutor.shutdownNow();
            Thread.currentThread().interrupt();
        }
        activeRules.clear();
    }

    /**
     * Obtiene estadísticas del engine.
     */
    public RuleEngineStatistics getStatistics() {
        RuleEngineStatistics stats = new RuleEngineStatistics();
        stats.totalRulesActive = activeRules.size();
        stats.rulesEvaluated = rulesEvaluated.get();
        stats.rulesAutoGenerated = rulesAutoGenerated.get();
        stats.rulesExpired = rulesExpired.get();
        stats.conflictsResolved = conflictsResolved.get();
        return stats;
    }

    /**
     * Resuelve conflictos entre reglas.
     * 
     * @param rules Lista de reglas que coinciden
     * @return La regla de mayor prioridad, o null si está vacía
     */
    @Nullable
    private FirewallRule resolveConflict(@NonNull List<FirewallRule> rules) {
        if (rules.isEmpty()) return null;
        
        // Ordenar por prioridad y recencia
        Collections.sort(rules);
        
        // Verificar conflictos específicos
        for (int i = 0; i < rules.size() - 1; i++) {
            FirewallRule current = rules.get(i);
            FirewallRule next = rules.get(i + 1);
            
            // Si misma prioridad y acciones contradictorias
            if (current.getPriority() == next.getPriority() && 
                current.getAction() != next.getAction()) {
                
                // Preferir BLOCK sobre otras acciones
                if (current.getAction() == RuleAction.BLOCK) {
                    return current;
                }
                if (next.getAction() == RuleAction.BLOCK) {
                    return next;
                }
                
                // Preferir QUARANTINE sobre ALERT/ALLOW
                if (current.getAction() == RuleAction.QUARANTINE) {
                    return current;
                }
                if (next.getAction() == RuleAction.QUARANTINE) {
                    return next;
                }
            }
        }
        
        // Retornar la de mayor prioridad
        conflictsResolved.incrementAndGet();
        return rules.get(0);
    }

    /**
     * Verifica si una nueva regla entra en conflicto con reglas existentes.
     * 
     * @param newRule Nueva regla a verificar
     * @return Lista de reglas en conflicto, o vacía si no hay conflicto
     */
    @NonNull
    public List<FirewallRule> checkConflicts(@NonNull FirewallRule newRule) {
        List<FirewallRule> conflicts = new ArrayList<>();
        
        for (FirewallRule existing : activeRules) {
            if (rulesConflict(newRule, existing)) {
                conflicts.add(existing);
            }
        }
        
        return conflicts;
    }

    /**
     * Verifica si dos reglas entran en conflicto.
     */
    private boolean rulesConflict(@NonNull FirewallRule r1, @NonNull FirewallRule r2) {
        // Mismo patrón de IPs y puertos pero acciones diferentes
        boolean samePattern = r1.sourceIPPattern.equals(r2.sourceIPPattern) &&
                            r1.destIPPattern.equals(r2.destIPPattern) &&
                            ((r1.sourcePort == null && r2.sourcePort == null) || 
                             (r1.sourcePort != null && r1.sourcePort.equals(r2.sourcePort))) &&
                            ((r1.destPort == null && r2.destPort == null) || 
                             (r1.destPort != null && r1.destPort.equals(r2.destPort)));
        
        return samePattern && r1.getAction() != r2.getAction();
    }

    /**
     * Estadísticas del engine.
     */
    public static final class RuleEngineStatistics {
        public int totalRulesActive;
        public long rulesEvaluated;
        public long rulesAutoGenerated;
        public long rulesExpired;
        public long conflictsResolved;

        @Override
        public String toString() {
            return String.format(
                    "RuleEngine{active=%d, evaluated=%d, autoGenerated=%d, expired=%d, conflicts=%d}",
                    totalRulesActive, rulesEvaluated, rulesAutoGenerated, rulesExpired, conflictsResolved
            );
        }
    }
}
